import { chromium } from '@playwright/test';
const b = await chromium.launch({executablePath:'/usr/local/bin/chromium',args:['--no-sandbox','--disable-dev-shm-usage','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader']});
const ctx = await b.newContext({ viewport: { width: 700, height: 900 } });
const p1 = await ctx.newPage();
const p2 = await ctx.newPage();
const errs = [];
p2.on('console', m => { if (m.type()==='error') errs.push(m.text()); });
await p1.goto('http://localhost:5288/', { waitUntil: 'load' });
await p1.waitForTimeout(15000);
await p1.evaluate(()=>window.__MD__?.enter?.());
await p2.goto('http://localhost:5288/', { waitUntil: 'load' });
await p2.waitForTimeout(15000);
await p2.evaluate(()=>window.__MD__?.enter?.());
await p2.waitForTimeout(5000);
console.log('peers p2:', JSON.stringify(await p2.evaluate(()=>window.__MD__.getSnapshot().peers)));
console.log('peers p1:', JSON.stringify(await p1.evaluate(()=>window.__MD__.getSnapshot().peers)));
console.log('errs:', errs.slice(0,3));
await b.close();
