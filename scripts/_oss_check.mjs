import { chromium } from '@playwright/test';
const b = await chromium.launch({executablePath:'/usr/local/bin/chromium',args:['--no-sandbox','--disable-dev-shm-usage','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader']});
const p = await (await b.newContext({viewport:{width:1400,height:800}})).newPage();
const errs=[], missing=[];
p.on('pageerror', e=>errs.push(String(e).slice(0,160)));
p.on('response', r=>{ if(r.status()>=400) missing.push(r.url().replace('http://localhost:5297','')); });
await p.goto('http://localhost:5297/3d/',{waitUntil:'load',timeout:90000});
await p.waitForTimeout(4500);
await p.waitForFunction(()=>window.__MD__,null,{timeout:90000});
await p.evaluate(()=>window.__MD__.enter());
await p.waitForTimeout(9000);
await p.evaluate(()=>window.__MD_TP__(0, 3.0));
await p.waitForTimeout(2500);
await p.evaluate(()=>window.__MD_FIXCAM__([0,2.2,9.2],[0.2,1.0,-4.0]));
await p.waitForTimeout(1500);
await p.screenshot({path:'/tmp/oss_hall.png',timeout:90000});
await p.evaluate(()=>window.__MD_TP__(-6.0, 38.0));
await p.waitForTimeout(2500);
await p.evaluate(()=>window.__MD_FIXCAM__([-3.0,3.0,34.0],[-7.0,1.2,40.0]));
await p.waitForTimeout(1500);
await p.screenshot({path:'/tmp/oss_yard.png',timeout:90000});
console.log('pageerror:', errs.length, errs.slice(0,3));
console.log('404/缺资产:', [...new Set(missing)].slice(0,8));
