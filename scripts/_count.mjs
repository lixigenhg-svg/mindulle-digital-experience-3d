import { chromium } from '@playwright/test';
const b = await chromium.launch({executablePath:'/usr/local/bin/chromium',args:['--no-sandbox','--disable-dev-shm-usage','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader']});
const p = await (await b.newContext({viewport:{width:900,height:600}})).newPage();
await p.goto('http://localhost:5288/',{waitUntil:'load'});
await p.waitForTimeout(6000);
await p.waitForFunction(()=>window.__MD__,null,{timeout:30000});
await p.evaluate(()=>{window.__MD__.enter();});
await p.waitForTimeout(1200);
await p.evaluate(()=>{window.__MD__.bowNow && window.__MD__.bowNow();});
await p.waitForTimeout(1500);
const r = await p.evaluate(()=>{const a=[];window.__SCENE__.traverse(o=>{if(o.isSkinnedMesh&&o.geometry.attributes.position.count===8297)a.push({v:o.visible,pos:o.getWorldPosition(new (o.position.constructor)()).toArray().map(n=>+n.toFixed(2)),scale:o.getWorldScale(new (o.position.constructor)()).toArray().map(n=>+n.toFixed(2))});});return a;});
console.log(JSON.stringify(r));
await b.close();
