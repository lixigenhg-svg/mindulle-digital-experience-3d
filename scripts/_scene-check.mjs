import { chromium } from '@playwright/test';
const b = await chromium.launch({executablePath:'/usr/local/bin/chromium',args:['--no-sandbox','--disable-dev-shm-usage','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader']});
const p = await b.newPage({ viewport: { width: 900, height: 1200 } });
p.on('pageerror', e=>console.log('ERR', e.message.slice(0,140)));
await p.goto('http://localhost:5288/', { waitUntil: 'load' });
await p.waitForTimeout(9000);
await p.evaluate(()=>window.__MD__.enter());
await p.waitForTimeout(2500);
await p.screenshot({ path: '/tmp/sc-idle.png' });
await p.evaluate(()=>window.__MD__.play('PRAY'));
await p.waitForTimeout(2500); await p.screenshot({ path: '/tmp/sc-pray.png' });
await p.evaluate(()=>window.__MD__.play('BOW'));
await p.waitForTimeout(2500); await p.screenshot({ path: '/tmp/sc-bow.png' });
await p.evaluate(()=>window.__MD__.play('WOODFISH'));
await p.waitForTimeout(2500); await p.screenshot({ path: '/tmp/sc-wood.png' });
await p.evaluate(()=>window.__MD__.play('IDLE'));
await p.waitForTimeout(1200);
await p.mouse.click(450, 600); await p.waitForTimeout(3500);
await p.screenshot({ path: '/tmp/sc-walk.png' });
console.log(JSON.stringify(await p.evaluate(()=>window.__MD__.getSnapshot())));
await b.close();
