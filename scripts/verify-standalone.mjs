import { chromium } from '@playwright/test';
const url='https://p9-flow-sign.byteimg.com/tos-cn-i-ik7evvg4ik/rc/pc/super_tool/80508712c7244094b0ce592f12ee9a56.html?lk3s=8e244e95&rcl=20261113172439A87407A89166E834EE3D&rrcfp=cb23d0ed&x-expires=1795167064&x-signature=S%2BjVnOJaj42q2fZAaKRzT2YQlPM%3D';
const b=await chromium.launch({executablePath:'/usr/local/bin/chromium',args:['--no-sandbox','--enable-unsafe-swiftshader']});
const p=await b.newPage({viewport:{width:390,height:844},deviceScaleFactor:2,isMobile:true,hasTouch:true});
const errors=[];
p.on('pageerror',e=>errors.push(String(e)));
p.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
p.on('requestfailed',r=>errors.push(`REQFAIL ${r.url()} ${r.failure()?.errorText}`));
await p.goto(url,{waitUntil:'networkidle',timeout:30000});
await p.waitForFunction(()=>window.__MD__,{timeout:15000});
await p.getByTestId('enter-button').tap();
await p.waitForFunction(()=>window.__MD__.getSnapshot().scene.ready,{timeout:15000});
await p.waitForTimeout(8000);
const s=await p.evaluate(()=>window.__MD__.getSnapshot());
console.log(JSON.stringify({errors,snapshot:s},null,2));
await p.screenshot({path:'docs/screenshots/07-standalone-mobile.png'});
await b.close();
