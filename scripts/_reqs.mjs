import { chromium } from '@playwright/test';
const b = await chromium.launch({executablePath:'/usr/local/bin/chromium',args:['--no-sandbox','--disable-dev-shm-usage','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader']});
const ctx = await b.newContext({viewport:{width:1400,height:800}});
const p = await ctx.newPage();
const urls = new Set();
p.on('request', r => { const u = r.url(); if (u.includes('/assets/') && !u.endsWith('.js') && !u.endsWith('.css')) urls.add(u.replace('http://localhost:5298/3d/','')); });
await p.goto('http://localhost:5298/3d/',{waitUntil:'load',timeout:120000});
await p.waitForTimeout(12000);
await p.evaluate(()=>window.__MD__.enter());
await p.waitForTimeout(12000);
await p.evaluate(()=>window.__MD_TP__(0,9));
await p.waitForTimeout(6000);
await p.evaluate(()=>window.__MD_TP__(0,31));
await p.waitForTimeout(8000);
await p.evaluate(()=>window.__MD_TP__(0,8));
await p.waitForTimeout(6000);
console.log([...urls].sort().join('\n'));
await b.close();
