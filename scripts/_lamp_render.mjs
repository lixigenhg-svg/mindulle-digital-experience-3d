import { chromium } from '@playwright/test';
const b = await chromium.launch({executablePath:'/usr/local/bin/chromium',args:['--no-sandbox','--disable-dev-shm-usage','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader']});
const ctx = await b.newContext({viewport:{width:1600,height:900}});
const p = await ctx.newPage();
let served = null;
await p.route('**/temple/lamp-list.php*', async route => {
  const r = await p.request.get('https://mindulle.kr/temple/lamp-list.php');
  served = (await r.text()).slice(0,200);
  await route.fulfill({ status:200, contentType:'application/json; charset=utf-8', body: served });
});
await p.goto('http://localhost:5298/3d/',{waitUntil:'load',timeout:120000});
await p.waitForTimeout(9000);
await p.evaluate(function(){ window.__MD__.enter(); });
await p.waitForTimeout(12000);
await p.evaluate(function(){ window.__MD_TP__(0, 40.0); });
await p.waitForTimeout(2500);
await p.evaluate(function(){ window.__MD_FACE__(Math.PI); });
await p.evaluate(function(){ window.__MD_FIXCAM__([0,1.85,38.6],[0,1.30,34.2]); });
await p.waitForTimeout(3000);
await p.screenshot({path:'/tmp/lamp_a.png',timeout:120000});
