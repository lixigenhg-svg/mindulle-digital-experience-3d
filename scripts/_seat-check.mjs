import { chromium } from '@playwright/test';
const b = await chromium.launch({executablePath:'/usr/local/bin/chromium',args:['--no-sandbox','--disable-dev-shm-usage','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader']});
const p = await b.newPage({ viewport: { width: 900, height: 1200 } });
await p.goto('http://localhost:5288/', { waitUntil: 'load' });
await p.waitForTimeout(16000);
await p.evaluate(()=>window.__MD__?.enter?.());
await p.waitForTimeout(3000);
await p.screenshot({ path: '/tmp/s1.png' });
await p.getByTestId('action-kowtow').click({ force: true });
await p.waitForTimeout(3200);
await p.screenshot({ path: '/tmp/s2.png' });
await p.waitForTimeout(3000);
await p.getByTestId('action-sit').click({ force: true });
await p.waitForTimeout(3200);
await p.screenshot({ path: '/tmp/s3.png' });
console.log(JSON.stringify(await p.evaluate(()=>window.__MD__.getSnapshot().player)));
await b.close();
