import { chromium, devices } from '@playwright/test';
const b = await chromium.launch({executablePath:'/usr/local/bin/chromium',args:['--no-sandbox','--disable-dev-shm-usage','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader']});
const p = await (await b.newContext({ ...devices['iPhone 13'], isMobile:true, hasTouch:true })).newPage();
p.on('console', m=>{ if(/temple/.test(m.text())) console.log('LOG', m.text()); });
await p.goto('http://localhost:5288/',{waitUntil:'load'});
await p.waitForTimeout(6000);
await p.waitForFunction(()=>window.__MD__,null,{timeout:30000});
await p.evaluate(()=>window.__MD__.enter());
await p.evaluate(()=>window.__MD_TP__(0, 2));
await p.waitForTimeout(800);
await p.evaluate(()=>window.__MD__.incenseNow());
for(let i=0;i<4;i++){ await p.waitForTimeout(1200);
  const st = await p.evaluate(()=>({pos:window.__MD_POS__(), hasFix:!!window.__MD_FIXCAM__, k:window.__MD_SCALE_K__}));
  console.log(i, JSON.stringify(st));
}
await p.screenshot({path:'/tmp/incB.png'});
await p.evaluate(()=>window.__MD_FIXCAM__([3.05,1.48,-4.98],[0,1.02,-5.95]));
await p.waitForTimeout(1500);
await p.screenshot({path:'/tmp/incC.png'});
await b.close();
