import { chromium } from '@playwright/test';
const b = await chromium.launch({executablePath:'/usr/local/bin/chromium',args:['--no-sandbox','--disable-dev-shm-usage','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader']});
const p = await (await b.newContext({viewport:{width:1400,height:820}})).newPage();
const errs=[]; p.on('pageerror',e=>errs.push(String(e).slice(0,140)));
await p.goto('https://mindulle.kr/3d/',{waitUntil:'load',timeout:120000});
await p.waitForTimeout(15000);
const keys = await p.evaluate(function(){ return Object.keys(window).filter(function(k){ return k.indexOf('TEMPLE') >= 0; }); });
console.log('A) TEMPLE键:', JSON.stringify(keys));
const methods = await p.evaluate(function(){ return window.__MD__ ? Object.keys(window.__MD__) : null; });
console.log('B) 方法:', JSON.stringify(methods));
console.log('C) 进殿前:', (await p.evaluate(function(){ return document.body.innerText.replace(/\s+/g,' ').slice(0,90); })));
const r = await p.evaluate(function(){ try { window.__MD__.enter(); return 'called'; } catch(e) { return 'err:' + e.message; } });
console.log('D) enter:', r);
await p.waitForTimeout(15000);
console.log('E) 进殿后:', (await p.evaluate(function(){ return document.body.innerText.replace(/\s+/g,' ').slice(0,110); })));
const keys2 = await p.evaluate(function(){ return Object.keys(window).filter(function(k){ return k.indexOf('TEMPLE') >= 0; }); });
console.log('F) 键:', JSON.stringify(keys2));
console.log('pageerror:', JSON.stringify(errs.slice(0,2)));
await b.close();
