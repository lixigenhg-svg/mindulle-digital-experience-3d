await p.waitForTimeout(600);
await p.evaluate(()=>{window.__MD_LOCK__=true; window.__MD_FIXCAM__([3.6,1.45,-5.55],[0,1.05,-5.55]); window.__MD_FACE__(0);});
await p.waitForTimeout(2000); await p.screenshot({path:'/tmp/pc1.png'});
await p.evaluate(()=>{window.__MD_FACE__(Math.PI/2);});
