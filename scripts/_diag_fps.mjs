import { chromium } from '@playwright/test';
const b = await chromium.launch({executablePath:'/usr/local/bin/chromium',args:['--no-sandbox','--disable-dev-shm-usage','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader']});
const p = await (await b.newContext({viewport:{width:800,height:520}})).newPage();
await p.goto('http://localhost:5296/3d/',{waitUntil:'load',timeout:90000});
await p.waitForTimeout(4000);
await p.waitForFunction(()=>window.__MD__,null,{timeout:90000});
await p.evaluate(()=>window.__MD__.enter());
await p.waitForTimeout(6000);
const fps = await p.evaluate(() => new Promise(res=>{let n=0;const t0=performance.now();const f=()=>{n++;if(performance.now()-t0<3000)requestAnimationFrame(f);else res(n/3);};requestAnimationFrame(f);}));
console.log('FPS:', fps.toFixed(1));
await p.evaluate(()=>window.__MD_TP__(0, 8));
await p.waitForTimeout(400);
await p.evaluate(()=>window.__MD_WALK__(0, 16));
await p.waitForTimeout(8000);
console.log('walk 8s to z=16 =>', JSON.stringify(await p.evaluate(()=>window.__MD_POS__?.())));
await b.close();
