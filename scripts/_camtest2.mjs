import { chromium, devices } from '@playwright/test';
const b = await chromium.launch({executablePath:'/usr/local/bin/chromium',args:['--no-sandbox','--disable-dev-shm-usage','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader']});
const ctx = await b.newContext({ ...devices['iPhone 13'], isMobile: true, hasTouch: true });
const p = await ctx.newPage();
await p.goto('http://localhost:5288/', { waitUntil: 'load' });
await p.waitForTimeout(6000);
await p.waitForFunction(()=>window.__MD__, null, {timeout:30000});
await p.evaluate(()=>window.__MD__.enter());
await p.waitForTimeout(1200);
await p.evaluate(()=>window.__MD_TP__(0.45, -5.75));
await p.evaluate(()=>window.__MD_FACE__(Math.atan2(-0.45, -1.2)));
await p.waitForTimeout(1500);
await p.evaluate(()=>window.__MD_CAM__(5.2,0.30,-0.75));
await p.waitForTimeout(1800);
await p.screenshot({path:'/tmp/cw0.png'});
await p.evaluate(()=>window.__MD_CAM__(3.0,0.26,-0.95));
await p.waitForTimeout(1600);
await p.screenshot({path:'/tmp/cw1.png'});
await b.close();
